// Writes chat-marks' hooks/boshiamy.mjs from the table in MyConfig's dot_surfingkeys.js (the
// BOSHIAMY-TABLE block gen-boshiamy.js generates from vi000246/vim-easymotion-boshiamy).
// usage (from the plugin folder): node scripts/gen-boshiamy.mjs <MyConfig>/dot_surfingkeys.js hooks/boshiamy.mjs
import fs from 'node:fs'

const [src, out] = process.argv.slice(2)
const text = fs.readFileSync(src, 'utf8')
const m = text.match(/const SK_BOSHIAMY2 = (\{[^\n]*\});/)
if (!m) throw new Error('SK_BOSHIAMY2 not found in ' + src)
const table = JSON.parse(m[1])
const keys = Object.keys(table)
if (keys.length < 600) throw new Error('only ' + keys.length + ' buckets')

const body = `// Boshiamy (嘸蝦米) two-letter buckets: BOSHIAMY2[ab] = the characters whose code starts with ab.
// Generated by scripts/gen-boshiamy.mjs, do not edit: from the BOSHIAMY-TABLE block of MyConfig's
// dot_surfingkeys.js, which scripts/surfingkeys/gen-boshiamy.js there makes from
// github.com/vi000246/vim-easymotion-boshiamy (liu7.cin, Boshiamy 7.0). A character whose code is
// one letter long is in no bucket.
export const BOSHIAMY2 = ${JSON.stringify(table)}
`
fs.writeFileSync(out, body)
console.log(`${keys.length} buckets, ${Object.values(table).join('').length} characters, ${body.length} bytes`)
